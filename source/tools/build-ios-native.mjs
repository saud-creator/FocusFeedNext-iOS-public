import { build } from 'vite';
import { fileURLToPath } from 'node:url';
import { readFile, writeFile } from 'node:fs/promises';
const root = fileURLToPath(new URL('../', import.meta.url));
await build({
  configFile: false,
  root,
  logLevel: 'warn',
  build: {
    target: 'safari16',
    outDir: 'src-tauri/plugins/ios-reader/ios/Sources',
    emptyOutDir: false,
    minify: true,
    lib: {
      entry: 'src-tauri/plugins/ios-reader/transaction/reader.ts',
      name: 'FfnReader',
      formats: ['iife'],
      fileName: () => 'Reader.js',
    },
  },
});
// Static Swift libraries do not automatically copy SwiftPM resource bundles
// into a Tauri archive. Compile the engine into the library itself.
const sources = new URL('../src-tauri/plugins/ios-reader/ios/Sources/', import.meta.url);
const script = await readFile(new URL('Reader.js', sources), 'utf8');
if (script.includes('"""##')) throw new Error('Unexpected Swift raw-string delimiter in the native engine.');
await writeFile(new URL('ReaderScript.swift', sources), '// Generated by tools/build-ios-native.mjs.\n' +
  'enum NativeReaderScript {\n    static let source = ##"""\n' + script + '\n"""##\n}\n');
